package S3Basics;

public class JavaComments {
    /**
     *
     * @param args
     * Defines the purpose of the method or the class
     */
    public static void main(String[] args) {
        //Single line
        //prints out a statement
        System.out.println("Hello Java developers");

        /*
         * Multi line comment
         * This usually allows the compiler to ignore a block of comments
         * */
        int x = 4;
        int y=3;
        int z=0;
        z = x+y;
        System.out.println("z= " + z);

    }
}
